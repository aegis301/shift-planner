export function t(locale: Locale, key: TranslationKey, vars?: Record<string, string>): string {
  let out: string = dictionaries[locale][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{{${k}}}`, v);
    }
  }
  return out;
}
